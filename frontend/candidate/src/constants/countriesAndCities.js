/**
 * Parses an existing location string into { country, city, customCity }
 * @param {string} rawLocation 
 * @returns {{ country: string, city: string, isCustomCity: boolean, customCity: string }}
 */
export function parseLocation(rawLocation) {
  if (!rawLocation || typeof rawLocation !== 'string') {
    return { country: 'India', city: 'Bangalore', isCustomCity: false, customCity: '' };
  }

  const clean = rawLocation.trim();
  if (!clean) {
    return { country: 'India', city: 'Bangalore', isCustomCity: false, customCity: '' };
  }

  // Check if comma-separated e.g. "Bangalore, India" or "Austin, TX, United States"
  for (const item of COUNTRIES_AND_CITIES) {
    // Check if ends with country name or includes it
    if (clean.toLowerCase().includes(item.country.toLowerCase())) {
      const remaining = clean.replace(new RegExp(item.country, 'i'), '').replace(/[,\s]+$/, '').replace(/^[,\s]+/, '').trim();
      
      // Match with known city in this country
      const matchedCity = item.cities.find(c => remaining.toLowerCase().includes(c.toLowerCase()) || c.toLowerCase().includes(remaining.toLowerCase()));
      if (matchedCity) {
        return { country: item.country, city: matchedCity, isCustomCity: false, customCity: '' };
      }
      if (remaining) {
        return { country: item.country, city: 'Other', isCustomCity: true, customCity: remaining };
      }
      return { country: item.country, city: item.cities[0], isCustomCity: false, customCity: '' };
    }
  }

  // Check if city name is in any country
  for (const item of COUNTRIES_AND_CITIES) {
    const matchedCity = item.cities.find(c => clean.toLowerCase().includes(c.toLowerCase().split(',')[0]));
    if (matchedCity) {
      return { country: item.country, city: matchedCity, isCustomCity: false, customCity: '' };
    }
  }

  // Fallback
  return { country: 'India', city: 'Other', isCustomCity: true, customCity: clean };
}
